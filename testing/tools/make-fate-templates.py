"""Writes main/src/woke/fate-read-data.ts: the pictures the Fate reader matches.

Inputs are game sprites cut from Art/UIImages1.txt (Augury/4k/*, Augury/CardArt/4k/*)
and one screenshot for the Confirm button, which has no sprite of its own.

  python make-fate-templates.py <icons dir> <card art dir> <screenshot> <confirm x,y,w,h> <screenshot card scale>

Everything is stored at NORM, half the 4K sprite size (1080p), and card-relative
pictures in the card frame's own coordinates (the 450x622 4K frame).
"""
import base64, json, os, sys
import numpy as np
from PIL import Image

NORM = 0.5
ART_SCALE = 0.25
ART_AT = (83, 135)  # card art's top left in the 4K frame
TOP_ROWS = (20, 118)  # banner strip of the frame used to find cards
TOP_TEXT = (110, 25, 340, 75)  # the name, which differs per card

ART_OF = {'Crowkeeper': 'CardArtEncirclingMurder', 'Sanguine': 'CardArtBloodDonut', 'Incandescent': 'CardArtBlackfireDetonations',
          'Rot': 'CardArtFlyingBroomsticks', 'Dryad': 'CardArtCorpsethornSlam', 'Deathbringer': 'CardArtOrbitalVisceraBeam',
          'Torchbearer': 'CardArtBonfire', 'Bloodthirsty': 'CardArtBloodboneProjectiles', 'Wildfire': 'CardArtBlackfireWalls',
          'Murderous': 'CardArtCrowBombs', 'Gravewalker': 'CardArtCorpseFissures', 'Houndmaster': 'CardArtHowlingWolves',
          'BlackFrost': 'CardArtIcicleFissures', 'Conjurer': 'CardArtCrowTunnel', 'Golemancer': 'CardArtTrudgingBloodGolem',
          'Doomsayer': 'CardArtBlackFireBlast', 'Avalanche': 'CardArtIcicleDarts', 'Butcher': 'CardArtTriggeredBloodGeysers',
          'Alchemist': 'CardArtCauldronFlip', 'Stormcaller': 'LightningLeylines', 'Tempest': 'CardArtLightningOrbs',
          'BloodMoon': 'CardArtBloodSplashes', 'Savage': 'BossSpawnSavage', 'Pestilent': 'BossSpawnFilth', 'Sadist': 'BossSpawnClassic'}
BARS = {'EmptyTwo': (2, 0), 'FillTwo1': (2, 1), 'FillTwo': (2, 2), 'EmptyThree': (3, 0), 'FillThree1': (3, 1), 'FillThree2': (3, 2), 'FillThree': (3, 3)}


def load(path, scale):
    im = Image.open(path).convert('RGBA')
    return im.resize((max(1, round(im.width * scale)), max(1, round(im.height * scale))), Image.LANCZOS)


def b64(a): return base64.b64encode(np.ascontiguousarray(a, np.uint8).tobytes()).decode()


def rgb_masked(im, alpha=60):
    a = np.asarray(im)
    return {'width': im.width, 'height': im.height, 'rgb': b64(a[:, :, :3]), 'mask': b64(a[:, :, 3] > alpha)}


icons, arts_dir, shot, box, shot_scale = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4], float(sys.argv[5])

frame = load(os.path.join(icons, 'AuguryCardFrame.png'), NORM)
top = np.asarray(frame)[round(TOP_ROWS[0] * NORM):round(TOP_ROWS[1] * NORM)].copy()
mask = top[:, :, 3] > 200
x0, y0, x1, y1 = (round(v * NORM) for v in TOP_TEXT)
mask[y0:y1, x0:x1] = False
gray = top[:, :, :3].astype(np.float32).mean(axis=2)
TOP = {'width': top.shape[1], 'height': top.shape[0], 'gray': b64(gray), 'mask': b64(mask), 'y': TOP_ROWS[0]}

ARTS = {}
for fate, name in ART_OF.items():
    a = np.asarray(load(os.path.join(arts_dir, name + '.png'), ART_SCALE))[:, :, :3]
    h, w = a.shape[:2]
    c = a[round(h * .2):round(h * .8), round(w * .2):round(w * .8)]
    ARTS[fate] = {'width': c.shape[1], 'height': c.shape[0], 'rgb': b64(c)}
art_full = Image.open(os.path.join(arts_dir, 'LightningLeylines.png'))
ART_BOX = {'x': ART_AT[0] + art_full.width * .2, 'y': ART_AT[1] + art_full.height * .2}

TIERS = {t: rgb_masked(load(os.path.join(icons, f'CardTier{t}.png'), NORM), 128) for t in (1, 2, 3)}
ICONS = {}
for f in sorted(os.listdir(icons)):
    if f.startswith('AuguryRewardIcon') and 'Backing' not in f:
        ICONS[f[16:-4]] = rgb_masked(load(os.path.join(icons, f), NORM))
BAR = {n: {**rgb_masked(load(os.path.join(icons, f'AuguryRewardSectionsBar{n}.png'), NORM)), 'need': need, 'filled': filled} for n, (need, filled) in BARS.items()}

x, y, w, h = (int(v) for v in box.split(','))
c = Image.open(shot).convert('L').crop((x, y, x + w, y + h))
c = c.resize((round(w * NORM / shot_scale), round(h * NORM / shot_scale)), Image.LANCZOS)
CONFIRM = {'width': c.width, 'height': c.height, 'gray': b64(np.asarray(c))}

out = os.path.join(os.path.dirname(__file__), '../../main/src/woke/fate-read-data.ts')
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by testing/tools/make-fate-templates.py from the game\'s Covens (Augury) UI sprites.\n')
    f.write('// Pictures are base64 bytes at NORM (half the 4K sprite size, so 1080p), RGB or grey, with\n')
    f.write('// masks of the pixels to compare. Card positions are in the 4K card frame (450x622).\n\n')
    for name, val in [('NORM', NORM), ('ART_SCALE', ART_SCALE), ('ART_BOX', ART_BOX), ('TOP', TOP), ('CONFIRM', CONFIRM),
                      ('TIERS', TIERS), ('BARS', BAR), ('ARTS', ARTS), ('ICONS', ICONS)]:
        f.write(f'export const {name} = {json.dumps(val, separators=(",", ": "))}\n')
print('wrote', out, os.path.getsize(out) // 1024, 'KB')
